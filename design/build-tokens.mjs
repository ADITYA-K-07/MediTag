// Generates platform theme files from design/tokens.json:
//   web/src/styles/tokens.css   (CSS custom properties, light + dark)
//   app/lib/theme/tokens.dart   (Dart constants)
// Usage: node design/build-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));
const HEADER = 'GENERATED by design/build-tokens.mjs from design/tokens.json. Do not edit by hand.';

const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());

function flatColors(colors) {
  const out = {};
  for (const [name, value] of Object.entries(colors)) {
    if (typeof value === 'string') out[name] = value;
    else for (const [tone, hex] of Object.entries(value)) out[name + tone[0].toUpperCase() + tone.slice(1)] = hex;
  }
  return out;
}

function hexToRgba(hex, alpha) {
  const n = parseInt(hex.slice(1), 16);
  return `rgba(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}, ${alpha})`;
}

function buildCss() {
  const light = flatColors(tokens.color);
  const dark = { ...light, ...tokens.colorDark };
  // In dark mode pastels become 12% tints of their strong colour.
  for (const [name, value] of Object.entries(tokens.color)) {
    if (typeof value === 'object') dark[name + 'Pastel'] = hexToRgba(value.strong, 0.16);
  }
  const vars = (map) => Object.entries(map).map(([k, v]) => `  --${kebab(k)}: ${v};`).join('\n');
  const e = tokens.motion.easing.join(', ');
  return `/* ${HEADER} */
:root {
${vars(light)}
  --radius-input: ${tokens.radius.input}px;
  --radius-card: ${tokens.radius.card}px;
  --radius-card-large: ${tokens.radius.cardLarge}px;
  --font-heading: '${tokens.font.heading}', system-ui, sans-serif;
  --font-body: '${tokens.font.body}', system-ui, sans-serif;
  --ease: cubic-bezier(${e});
  --motion-fast: ${tokens.motion.fastMs}ms;
  --motion-base: ${tokens.motion.baseMs}ms;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(dark).replace(/^/gm, '  ')}
  }
}
:root[data-theme="dark"] {
${vars(dark)}
}
`;
}

function buildDart() {
  const colors = flatColors(tokens.color);
  const darkColors = tokens.colorDark;
  const c = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
  const lines = Object.entries(colors).map(([k, v]) => `  static const ${k} = ${c(v)};`).join('\n');
  const darkLines = Object.entries(darkColors).map(([k, v]) => `  static const ${k} = ${c(v)};`).join('\n');
  const [x1, y1, x2, y2] = tokens.motion.easing;
  return `// ${HEADER}
import 'package:flutter/animation.dart';

abstract final class MtColors {
${lines}
}

abstract final class MtColorsDark {
${darkLines}
}

abstract final class MtRadius {
  static const input = ${tokens.radius.input}.0;
  static const card = ${tokens.radius.card}.0;
  static const cardLarge = ${tokens.radius.cardLarge}.0;
  static const pill = ${tokens.radius.pill}.0;
}

abstract final class MtMotion {
  static const fast = Duration(milliseconds: ${tokens.motion.fastMs});
  static const base = Duration(milliseconds: ${tokens.motion.baseMs});
  static const easing = Cubic(${x1}, ${y1}, ${x2}, ${y2});
}

abstract final class MtFonts {
  static const heading = '${tokens.font.heading}';
  static const body = '${tokens.font.body}';
}

abstract final class MtTouch {
  static const min = ${tokens.touch.min}.0;
  static const emergencyButton = ${tokens.touch.emergencyButton}.0;
}
`;
}

function write(rel, content) {
  const path = join(root, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log('wrote', rel);
}

write('web/src/styles/tokens.css', buildCss());
write('app/lib/theme/tokens.dart', buildDart());
