// Writes schema/test-vectors.json: envelopes signed with a throwaway TEST key, so the website and the
// Flutter app can check they decode and verify tags exactly like the server. Never use this key in production.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { encodeEnvelope } from '../lib/core/envelope.js';
import { planTagWrite } from '../lib/core/tagWrite.js';
import { generateSigningKeyPair, rawPublicKey, signBytes } from '../lib/core/signing.js';

const keys = generateSigningKeyPair();
const other = generateSigningKeyPair();
const profile = {
  name: 'Rahul Sharma',
  dob: '1998-04-12',
  bloodGroup: 'B+',
  allergies: ['Penicillin', 'Peanuts'],
  conditions: ['Type 1 Diabetes'],
  medications: ['Insulin glargine 20u'],
  organDonor: true,
  emergencyContacts: [{ name: 'Priya Sharma', relation: 'Mother', phone: '+919876543210' }],
  onTagFields: { dob: true, bloodGroup: true, allergies: true, conditions: true, medications: true, organDonor: true, emergencyContacts: true },
};
const plan = planTagWrite({
  profile,
  tagId: 'k8Fq2xLm9Pz4Rt7W',
  baseUrl: 'https://meditag.app',
  signingKey: keys.privateKeyPem,
  keyId: 1,
  now: Date.UTC(2026, 9, 31, 12),
});
const valid = Buffer.from(plan.envelope, 'base64');

const tampered = Buffer.from(valid);
const bgAt = tampered.indexOf('"B+"');
tampered[bgAt + 1] = 'O'.charCodeAt(0); // blood group B+ -> O+

const json = Buffer.from('{"v":1,"tid":"k8Fq2xLm9Pz4Rt7W","n":"Fake Person","ts":1761912000}');
const wrongKey = Buffer.from(encodeEnvelope({ json, keyId: 1, signature: signBytes(json, other.privateKeyPem) }));

const vectors = {
  $comment: 'TEST KEY ONLY. Generated by functions/scripts/make-test-vectors.mjs.',
  publicKeyHex: Buffer.from(rawPublicKey(keys.publicKeyPem)).toString('hex'),
  cases: [
    { name: 'valid', envelopeHex: valid.toString('hex'), expectValid: true, expectPayload: JSON.parse(valid.subarray(3, 3 + valid.readUInt16BE(1)).toString()) },
    { name: 'tampered-blood-group', envelopeHex: tampered.toString('hex'), expectValid: false },
    { name: 'signed-by-other-key', envelopeHex: wrongKey.toString('hex'), expectValid: false },
    { name: 'truncated', envelopeHex: valid.subarray(0, 40).toString('hex'), expectError: true },
  ],
  uri: plan.uri,
  bytesNeeded: plan.bytesNeeded,
};
// The website and app demo modes bundle their own copies (neither can load files outside its folder).
for (const rel of ['../../schema/test-vectors.json', '../../web/src/lib/demo/test-vectors.json', '../../app/assets/demo/test-vectors.json']) {
  const out = join(import.meta.dirname, rel);
  writeFileSync(out, JSON.stringify(vectors, null, 2) + '\n');
  console.log('wrote', out);
}
console.log(`payload uses ${plan.bytesNeeded} of 888 tag bytes`);
